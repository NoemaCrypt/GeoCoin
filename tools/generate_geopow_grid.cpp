// Reproduce the v1 latitude-band CDF from pinned GeographicLib 2.3.0.
#include <GeographicLib/Ellipsoid.hpp>
#include <GeographicLib/Math.hpp>
#include <GeographicLib/Constants.hpp>
#include <cmath>
#include <cstdint>
#include <array>
#include <iostream>
int main() {
    GeographicLib::Ellipsoid earth(GeographicLib::Constants::WGS84_a(), GeographicLib::Constants::WGS84_f());
    std::array<uint64_t, 1801> cdf{};
    for (size_t i = 0; i <= 900; ++i) {
        const double latitude = -90 + i / 10.0;
        cdf[i] = static_cast<uint64_t>(std::llround((1 + GeographicLib::Math::sind(earth.AuthalicLatitude(latitude))) * 2147483648.0));
    }
    for (size_t i = 901; i <= 1800; ++i) cdf[i] = 4294967296ULL - cdf[1800 - i];
    std::cout << "#pragma once\n#include <array>\n#include <cstdint>\n\nnamespace geocoin::consensus::geo {\n"
        "// WGS84 band areas, quantized to 2^32 equiprobable tickets.\n"
        "// Generated by tools/generate_geopow_grid.cpp with GeographicLib 2.3.0.\n"
        "inline constexpr std::array<uint64_t, 1801> kLatitudeCdf{\n";
    for (size_t i = 0; i < cdf.size(); ++i) {
        if (i % 8 == 0) std::cout << "    ";
        std::cout << cdf[i] << "ULL,";
        if (i % 8 == 7 || i + 1 == cdf.size()) std::cout << '\n';
        else std::cout << ' ';
    }
    std::cout << "};\n} // namespace geocoin::consensus::geo\n";
}
